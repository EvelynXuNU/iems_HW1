"""Audit completed Part 2 evidence without importing its learning implementation.

Reconstruct every lagged EMA from saved episode returns, check first-ten-step
credit assignment, and recompute frozen evaluation statistics. No training,
game rollouts, or GPU access is performed. This supplements the exact-gradient
and controlled variance experiments in validate_q3.py; it cannot prove that
a stored trajectory was generated by the claimed environment.
"""
import csv
import hashlib
import json
import math
import statistics
from pathlib import Path

import torch


def read_csv(path):
    with path.open() as stream:
        return list(csv.DictReader(stream))


def close(actual, expected):
    error = abs(float(actual) - float(expected))
    if not math.isfinite(error) or error > 1e-10:
        raise AssertionError(f"{actual} differs from {expected}")
    return error


def flag(value):
    if value not in ("True", "False"):
        raise AssertionError(f"Invalid boolean: {value}")
    return value == "True"


def audit_run(root, expected_episodes, evaluation_folder="evaluation_trained"):
    checkpoint = root / "checkpoint.pt"
    saved = torch.load(checkpoint, map_location="cpu", weights_only=False)
    config = saved["config"]
    history = read_csv(root / "training.csv")
    updates = read_csv(root / "updates.csv") if (root / "updates.csv").exists() else saved["updates"]
    assert len(history) == len(saved["history"]) == expected_episodes
    assert len(updates) == len(saved["updates"])
    gamma = .95 if config["game"] == "cartpole" else .99
    numerator = mass = 0.
    decay = saved["baseline_state"]["decay"]
    previous = 0
    max_error = 0.
    for index, update in enumerate(updates):
        through = int(update["through_episode"])
        batch = history[previous:through]
        baseline = numerator / mass if mass else 0.
        assert len(batch) == int(update["batch_episodes"]) > 0
        assert len(batch) <= config["batch_episodes"]
        max_error = max(max_error, close(update["baseline_used"], baseline))
        for episode, row in enumerate(batch, previous + 1):
            assert int(row["episode"]) == episode
            assert int(row["seed"]) == config["seed"] + episode - 1
            assert flag(row["terminated"]) or flag(row["truncated"])
            max_error = max(max_error, close(row["baseline_used"], baseline))
            original = saved["history"][episode - 1]
            for key in ("score", "discounted_return", "length", "baseline_used"):
                close(row[key], original[key])
            if config["game"] == "cartpole":
                close(row["score"], row["length"])
                close(row["discounted_return"], (1 - gamma ** int(row["length"])) / (1 - gamma))
        target = statistics.mean(float(row["discounted_return"]) for row in batch)
        numerator = decay * numerator + (1 - decay) * target
        mass = decay * mass + (1 - decay)
        max_error = max(max_error, close(update["baseline_for_next_batch"], numerator / mass))
        for key in ("baseline_used", "baseline_for_next_batch"):
            close(update[key], saved["updates"][index][key])
        previous = through
    assert previous == expected_episodes
    state = saved["baseline_state"]
    close(state["numerator"], numerator)
    close(state["mass"], mass)
    assert state["episodes_seen"] == expected_episodes
    assert state["batches_seen"] == len(updates)
    trace_steps = 0
    for path in sorted(root.glob("first_10*steps*.json")):
        for row in json.loads(path.read_text()):
            baseline = row["baseline_used"]
            advantage = row["reward_to_go"] - baseline
            close(row["advantage"], advantage)
            close(row["gradient_weight"], gamma ** row["step"] * advantage / config["reward_scale"])
            assert row["environment_action"] == row["policy_action"] + (2 if config["game"] == "pong" else 0)
            trace_steps += 1
    evaluation = root / evaluation_folder
    measured = json.loads((evaluation / "evaluation.json").read_text())
    episodes = read_csv(evaluation / "episodes.csv")
    scores = [float(row["score"]) for row in episodes]
    assert len(episodes) == measured["episodes"] == 500
    close(measured["mean"], statistics.mean(scores))
    close(measured["sample_standard_deviation"], statistics.stdev(scores))
    close(measured["population_standard_deviation"], statistics.pstdev(scores))
    close(measured["min"], min(scores))
    close(measured["max"], max(scores))
    close(measured["discounted_return_mean"], statistics.mean(float(r["discounted_return"]) for r in episodes))
    for name in ("terminated", "truncated"):
        assert measured[name + "_episodes"] == sum(flag(r[name]) for r in episodes)
    assert all(flag(r["terminated"]) or flag(r["truncated"]) for r in episodes)
    seed = measured["evaluation_seed"]
    assert {int(r["seed"]) for r in episodes} == set(range(seed, seed + 500))
    assert not ({int(r["seed"]) for r in episodes} & {int(r["seed"]) for r in history})
    assert measured["training_episodes"] == expected_episodes
    assert hashlib.sha256(checkpoint.read_bytes()).hexdigest() == measured["checkpoint_sha256"]
    if config["game"] == "pong":
        close(measured["win_fraction"], sum(s > 0 for s in scores) / 500)
    else:
        close(measured["cartpole_500_fraction"], sum(s == 500 for s in scores) / 500)
    assert (root / "training_rewards.png").is_file()
    assert (evaluation / "reward_histogram.png").is_file()
    return {"directory": str(root), "training_episodes": expected_episodes,
            "actor_updates": len(updates), "max_baseline_reconstruction_error": max_error,
            "trace_steps_checked": trace_steps, "evaluation_episodes": len(scores),
            "mean": statistics.mean(scores), "sample_sd": statistics.stdev(scores),
            "checkpoint_matches_evaluation": True,
            "training_and_evaluation_reset_banks_disjoint": True}


def main():
    roots = [(Path("results/q3/cartpole") / name, 6000, "evaluation_trained")
             for name in ("final_seed3817", "seed3818", "seed3819")]
    roots += [(Path("results/q3/pong/seed3817_lr001"), 10000, "evaluation_trained"),
              (Path("results/pong_tuning/selected_model"), 4480, "evaluation_final")]
    evidence = {"status": "passed", "scope": "saved-artifact audit; no new training or evaluation",
                "runs": [audit_run(*args) for args in roots]}
    output = Path("results/q3/verifier/completed_artifact_audit.json")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(evidence, indent=2) + "\n")
    print(json.dumps(evidence, indent=2))


if __name__ == "__main__":
    main()
